'use strict';

const test = require('node:test');
const assert = require('node:assert');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const { computeTransactionRewardV2 } = require('../src/reward_math_v2');
const { TRANSFORM_VERSION_V2 } = require('../scripts/catalogue_v2/transform');
const { loadVerifiedSlugs } = require('../scripts/catalogue_v2/overrides');

/**
 * Plan §7 "Real cards" (WP7): every issuer-verified worked example
 * (db/fixtures/card_worked_examples, C6) runs through the JS engine v2
 * against the card as the loader would publish it — the snapshots in
 * db/fixtures/catalogue_v2_cards, generated by
 * api/scripts/catalogue_v2/snapshot_examples.js from the CardPipeline record,
 * its override file and the merchant directory.
 *
 * Compared per example: the expected currency's amount, value_inr (when the
 * example gives one), excluded, and cap deltas summed per CardPipeline cap id
 * (every emitted cap of a source id counts). State before the transaction is
 * set on every emitted cap of the named source id.
 *
 * Known failures (db/fixtures/catalogue_v2_cards/_known_failures.json) must
 * still fail, so a fix is noticed. Examples with engine_checkable false (C8
 * D14a) are reported as skipped with their reason. The Dart twin is
 * packages/pandapay_domain/test/card_worked_examples_test.dart.
 */

const REPO = path.join(__dirname, '..', '..');
const EXAMPLES_DIR = path.join(REPO, 'db', 'fixtures', 'card_worked_examples');
const SNAPSHOT_DIR = path.join(REPO, 'db', 'fixtures', 'catalogue_v2_cards');
const DIRECTORY_FILE = path.join(REPO, 'db', 'fixtures', 'merchant_directory.json');
const OVERRIDES_DIR = path.join(REPO, 'api', 'scripts', 'catalogue_overrides');
const ENGINE = 'js';

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const sha256 = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

/** Half-up to 2 dp (C8 D12e). */
function money2(value) {
  return Math.round(value * 100 + 1e-6) / 100;
}

const exampleFiles = fs.readdirSync(EXAMPLES_DIR).filter((f) => f.endsWith('.json')).sort();
const examplesBySlug = new Map(exampleFiles.map((f) => {
  const doc = readJson(path.join(EXAMPLES_DIR, f));
  return [doc.source_slug, doc];
}));
// WP7 probes (catalogue_v2_cards/_probes.json): cards changed by a WP7 override
// with no worked-examples file. Checked like examples; never verified.
const probesBySlug = new Map(Object.entries(readJson(path.join(SNAPSHOT_DIR, '_probes.json')).cards)
  .map(([slug, doc]) => [slug, { source_slug: slug, ...doc }]));
const directoryFile = readJson(path.join(SNAPSHOT_DIR, '_directory.json'));
const directory = { merchants: directoryFile.merchants, platforms: directoryFile.platforms };
const knownFailures = readJson(path.join(SNAPSHOT_DIR, '_known_failures.json')).failures;
const verifiedSlugs = loadVerifiedSlugs(OVERRIDES_DIR);

function snapshotFor(slug) {
  const file = path.join(SNAPSHOT_DIR, `${slug}.json`);
  return fs.existsSync(file) ? readJson(file) : null;
}

/**
 * The C3.1 context the engines take. Worked examples name the app category
 * by slug; the snapshot's category ids are `cat-<slug>` (catalogue_v2/wire.js).
 * Some examples write the MCC as a number; the contract says a 4-digit string.
 */
function engineContext(ctx) {
  const out = { ...ctx };
  if (out.category_id == null && out.category_slug) out.category_id = `cat-${out.category_slug}`;
  if (typeof out.mcc === 'number') out.mcc = String(out.mcc).padStart(4, '0');
  return out;
}

function capIdsBySource(card) {
  const map = new Map();
  for (const cap of card.cap_rules) {
    if (!map.has(cap.source_local_id)) map.set(cap.source_local_id, []);
    map.get(cap.source_local_id).push(cap.id);
  }
  return map;
}

/**
 * C8 D25a: an example may allow the engine to under-state points by at most
 * 1 (`expect.tolerance_points`, with `expect.tolerance_note` citing the
 * issuer's own arithmetic) where the issuer rounds base and bonus separately.
 * Anything else (above 1, negative, not an integer, or no note) is rejected.
 */
function toleranceOf(expect) {
  const raw = expect.tolerance_points;
  if (raw === undefined || raw === null) return { points: 0 };
  if (!Number.isInteger(raw) || raw < 0 || raw > 1) return { error: `tolerance_points must be 0 or 1 (C8 D25a), got ${JSON.stringify(raw)}` };
  if (raw > 0 && !(typeof expect.tolerance_note === 'string' && expect.tolerance_note.trim())) return { error: 'tolerance_points needs a tolerance_note citing the issuer arithmetic (C8 D25a)' };
  return { points: raw };
}

/** actual in [expected − tolerance, expected] (2 dp): may under-state, never over-state. */
function withinTolerance(actual, expected, tolerance) {
  const a = money2(actual);
  const e = money2(expected);
  return a <= e && a >= money2(e - tolerance);
}

/** Runs one example; returns the list of mismatches (empty = pass). */
function checkExample(card, example) {
  const bySource = capIdsBySource(card);
  const sourceOfCap = new Map(card.cap_rules.map((cap) => [cap.id, cap.source_local_id]));
  const consumed = {};
  for (const [source, value] of Object.entries(example.state_before?.caps_by_source_id || {})) {
    for (const id of bySource.get(source) || []) consumed[id] = value;
  }
  const result = computeTransactionRewardV2({
    card,
    rewardRules: card.reward_rules,
    capRules: card.cap_rules,
    capConsumedBefore: consumed,
    ctx: engineContext(example.ctx),
    directory,
  });

  const expect = example.expect;
  const problems = [];
  const tol = toleranceOf(expect);
  if (tol.error) return [tol.error];
  if (Boolean(result.excluded) !== Boolean(expect.excluded)) problems.push(`excluded ${result.excluded}, expected ${expect.excluded}`);

  // Currency: the expected currency's field is present (C8 D12f), and nothing
  // is earned in the other currency.
  const isPoints = expect.currency === 'points';
  const actual = isPoints ? result.points : result.cashbackInr;
  const other = isPoints ? result.cashbackInr : result.points;
  if (actual == null) problems.push(`currency: no ${isPoints ? 'points' : 'cashback_inr'} in the result, expected ${expect.currency}`);
  else if (!withinTolerance(actual, Number(expect.amount), isPoints ? tol.points : 0)) problems.push(`${isPoints ? 'points' : 'cashback_inr'} ${actual}, expected ${expect.amount}`);
  if (other != null && money2(other) !== 0) problems.push(`currency: earned ${other} in ${isPoints ? 'cashback_inr' : 'points'}, expected ${expect.currency} only`);

  const pointValue = Number(card.point_value_inr) || 0;
  if (expect.value_inr != null && !withinTolerance(result.valueInr, Number(expect.value_inr), isPoints ? tol.points * pointValue : 0)) {
    problems.push(`value_inr ${result.valueInr}, expected ${expect.value_inr}`);
  }

  const gotDeltas = {};
  for (const [capId, delta] of Object.entries(result.capDeltas || {})) {
    const source = sourceOfCap.get(capId) ?? capId;
    gotDeltas[source] = money2((gotDeltas[source] || 0) + delta);
  }
  const wantDeltas = {};
  for (const [source, delta] of Object.entries(expect.cap_deltas_by_source_id || {})) {
    if (Number(delta) !== 0) wantDeltas[source] = money2(Number(delta));
  }
  const pointsCapSources = new Set(card.cap_rules.filter((cap) => String(cap.cap_kind).endsWith('_points')).map((cap) => cap.source_local_id));
  for (const source of new Set([...Object.keys(gotDeltas), ...Object.keys(wantDeltas)])) {
    const capTol = pointsCapSources.has(source) ? tol.points : 0;
    if (!withinTolerance(gotDeltas[source] ?? 0, wantDeltas[source] ?? 0, capTol)) {
      const note = bySource.has(source) ? '' : ' (cap not emitted)';
      problems.push(`cap ${source} delta ${gotDeltas[source] ?? 0}, expected ${wantDeltas[source] ?? 0}${note}`);
    }
  }
  return problems;
}

test('D25a tolerance: the engine may be 1 point under, never over; tolerance above 1 is rejected', () => {
  const tol = toleranceOf({ tolerance_points: 1, tolerance_note: 'issuer rounds base and bonus separately' });
  assert.deepStrictEqual(tol, { points: 1 });
  assert.ok(withinTolerance(1055, 1056, tol.points), 'engine 1 below passes');
  assert.ok(withinTolerance(1056, 1056, tol.points), 'exact passes');
  assert.ok(!withinTolerance(1057, 1056, tol.points), 'engine 1 above fails');
  assert.ok(!withinTolerance(1054, 1056, tol.points), 'engine 2 below fails');
  assert.ok(!withinTolerance(1055, 1056, 0), 'no tolerance: exact only');
  assert.match(toleranceOf({ tolerance_points: 2, tolerance_note: 'x' }).error, /0 or 1/);
  assert.match(toleranceOf({ tolerance_points: 0.5, tolerance_note: 'x' }).error, /0 or 1/);
  assert.deepStrictEqual(toleranceOf({ tolerance_points: 1.0, tolerance_note: 'x' }), { points: 1 }, 'an integral number is accepted (Dart accepts 1.0 too)');
  assert.match(toleranceOf({ tolerance_points: 1 }).error, /tolerance_note/);
  // An example carrying tolerance 2 fails the harness even when the engine matches exactly.
  const card = snapshotFor('tata-neu-infinity-hdfc-bank').card;
  const example = examplesBySlug.get('tata-neu-infinity-hdfc-bank').examples.find((e) => e.id === '004');
  assert.deepStrictEqual(checkExample(card, example), [], 'the issuer example passes with tolerance 1');
  const tooLoose = { ...example, expect: { ...example.expect, tolerance_points: 2 } };
  assert.match(checkExample(card, tooLoose).join(' '), /0 or 1/);
});

test('every worked-example card has a current snapshot', () => {
  assert.ok(examplesBySlug.size > 0);
  const directoryHash = sha256(DIRECTORY_FILE);
  assert.strictEqual(directoryFile.directory_sha256, directoryHash,
    'catalogue_v2_cards/_directory.json is stale: run node api/scripts/catalogue_v2/snapshot_examples.js');
  for (const slug of [...examplesBySlug.keys(), ...probesBySlug.keys()]) {
    const snap = snapshotFor(slug);
    assert.ok(snap, `no snapshot for ${slug}: run node api/scripts/catalogue_v2/snapshot_examples.js`);
    const stale = `${slug} snapshot is stale: run node api/scripts/catalogue_v2/snapshot_examples.js`;
    assert.strictEqual(snap.source_slug, slug);
    assert.strictEqual(snap.inputs.transform_version, TRANSFORM_VERSION_V2, stale);
    assert.strictEqual(snap.inputs.directory_sha256, directoryHash, stale);
    const overrideFile = path.join(OVERRIDES_DIR, `${slug}.json`);
    assert.strictEqual(snap.inputs.override_sha256, fs.existsSync(overrideFile) ? sha256(overrideFile) : null, stale);
    assert.strictEqual(snap.inputs.verified, verifiedSlugs.has(slug), stale);
    assert.ok(Array.isArray(snap.card.reward_rules) && Array.isArray(snap.card.cap_rules));
  }
});

test('the known-failures list names only real, engine-checkable examples', () => {
  for (const [key, entry] of Object.entries(knownFailures)) {
    const [slug, id] = key.split('#');
    const doc = examplesBySlug.get(slug);
    assert.ok(doc, `${key}: no worked-example file`);
    const example = doc.examples.find((e) => e.id === id);
    assert.ok(example, `${key}: no such example`);
    assert.notStrictEqual(example.engine_checkable, false, `${key}: not engine-checkable, so it can't be a known failure`);
    assert.ok(['example_wrong', 'research_data', 'directory_data', 'loader_bug', 'engine_bug'].includes(entry.category), `${key}: category`);
    assert.ok(Array.isArray(entry.engines) && entry.engines.length, `${key}: engines`);
    assert.ok(entry.routed_to && entry.summary, `${key}: routed_to and summary`);
  }
});

test('verified_cards.json lists only cards whose examples all pass and that carry no blocking flag (C8 D18j)', () => {
  for (const slug of verifiedSlugs) {
    const doc = examplesBySlug.get(slug);
    assert.ok(doc, `${slug}: verified without worked examples`);
    const known = Object.keys(knownFailures).filter((k) => k.startsWith(`${slug}#`));
    assert.deepStrictEqual(known, [], `${slug}: verified but has known failures`);
    const snap = snapshotFor(slug);
    assert.deepStrictEqual(snap.blocking_flags, [], `${slug}: verified but blocked by ${snap.blocking_flags}`);
    assert.strictEqual(snap.card.model_status, 'verified', `${slug}: snapshot model_status`);
  }
});

for (const [slug, doc] of examplesBySlug) {
  const snap = snapshotFor(slug);
  for (const example of doc.examples) {
    const key = `${slug}#${example.id}`;
    const name = `${key} ${example.title}`;
    if (example.engine_checkable === false) {
      test(name, { skip: `not engine-checkable: ${example.not_checkable_reason || 'no reason given'}` }, () => {});
      continue;
    }
    const known = knownFailures[key];
    if (known && known.engines.includes(ENGINE)) {
      test(`${name} [known failure: ${known.category} -> ${known.routed_to}]`, () => {
        assert.ok(snap, `no snapshot for ${slug}`);
        const problems = checkExample(snap.card, example);
        assert.ok(problems.length > 0,
          `${key} now passes: remove it from db/fixtures/catalogue_v2_cards/_known_failures.json (and consider verified_cards.json)`);
      });
      continue;
    }
    test(name, () => {
      assert.ok(snap, `no snapshot for ${slug}`);
      const problems = checkExample(snap.card, example);
      assert.deepStrictEqual(problems, [], `${key}: ${example.why}`);
    });
  }
}

for (const [slug, doc] of probesBySlug) {
  assert.ok(!examplesBySlug.has(slug), `${slug}: has worked examples, so it is not a probe card`);
  assert.ok(!verifiedSlugs.has(slug), `${slug}: a probe card is never verified`);
  for (const example of doc.examples) {
    test(`probe ${slug}#${example.id} ${example.title}`, () => {
      const snap = snapshotFor(slug);
      assert.ok(snap, `no snapshot for ${slug}`);
      assert.deepStrictEqual(checkExample(snap.card, example), [], `${slug}#${example.id}: ${example.why}`);
    });
  }
}
